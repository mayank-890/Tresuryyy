CPP_TYPES = {
    "u8": ("uint8_t", "B"),
    "u16": ("uint16_t", "H"),
    "u32": ("uint32_t", "I"),
    "u64": ("uint64_t", "Q"),
    "i32": ("int32_t", "i"),
    "i64": ("int64_t", "q"),
    "ascii4": ("std::array<char, 4>", None),
}


def cpp_enum_name(enum_name: str, member: str) -> str:
    return f"{enum_name}{member}"


def py_enum_name(enum_name: str, member: str) -> str:
    return f"{enum_name}.{member}"


def field_cpp_type(field: dict[str, Any], enums: dict[str, Any]) -> str:
    ftype = field["type"]
    if ftype in CPP_TYPES:
        return CPP_TYPES[ftype][0]
    if ftype == "bytes32":
        return "std::array<std::byte, 32>"
    if ftype == "ascii":
        return f"std::array<char, {field['size']}>"
    if ftype == "utf8":
        return "std::string"
    if ftype == "enum":
        return field["enum"]
    raise ValueError(f"unknown field type {ftype!r}")


def field_py_annotation(field: dict[str, Any]) -> str:
    ftype = field["type"]
    if ftype in {"u8", "u16", "u32", "u64", "i32", "i64"}:
        return "int"
    if ftype == "bytes32":
        return "bytes"
    if ftype == "ascii4":
        return "str"
    if ftype == "ascii":
        return "str"
    if ftype == "utf8":
        return "str"
    if ftype == "enum":
        return "int"
    raise ValueError(f"unknown field type {ftype!r}")


def emit_cpp(schema: dict[str, Any]) -> str:
    enums = schema["enums"]
    records = schema["records"]
    magic = schema["magic"]
    lines: list[str] = []
    w = lines.append

    w("#pragma once")
    w("// Generated by schemas/codegen/generate.py — do not edit.")
    w("")
    w("#include <array>")
    w("#include <cstddef>")
    w("#include <cstdint>")
    w("#include <cstring>")
    w("#include <span>")
    w("#include <string>")
    w("#include <type_traits>")
    w("#include <vector>")
    w("")
    w("namespace trading::journal::v1 {")
    w("")
    w(f"inline constexpr char kJournalMagic[4] = {{'{magic[0]}', '{magic[1]}', '{magic[2]}', '{magic[3]}'}};")
    w(f"inline constexpr std::uint16_t kFormatVersion = {schema['format_version']};")
    w("inline constexpr std::size_t kRecordHeaderSize = 40;")
    w("")
    w(_cpp_crc32c())
    w("")
    for enum_name, members in enums.items():
        w(f"enum class {enum_name} : std::uint16_t {{")
        for member in members:
            w(f"  {member['name']} = {member['value']},")
        w("};")
        w("")
    w("enum class RecordType : std::uint16_t {")
    for rec in records:
        w(f"  {rec['name']} = {rec['id']},")
    w("};")
    w("")
    w("#pragma pack(push, 1)")
    w("struct RecordHeader {")
    w("  char magic[4]{};")
    w("  std::uint16_t format_version{};")
    w("  std::uint16_t record_type{};")
    w("  std::uint64_t sequence{};")
    w("  std::uint64_t monotonic_ns{};")
    w("  std::uint64_t wall_ns{};")
    w("  std::uint32_t payload_length{};")
    w("  std::uint32_t crc32c{};")
    w("};")
    w("#pragma pack(pop)")
    w("")
    w("static_assert(sizeof(RecordHeader) == kRecordHeaderSize);")
    for field in schema["header"]["fields"]:
        name = field["name"]
        off = field["offset"]
        w(f"static_assert(offsetof(RecordHeader, {name}) == {off});")
    w("")
    w(_cpp_header_codec())
    w("")

    for rec in records:
        name = rec["name"]
        w(f"struct {name}Payload {{")
        for field in rec["fields"]:
            w(f"  {field_cpp_type(field, enums)} {field['name']}{{}};")
        w("};")
        w("")
        w(f"[[nodiscard]] inline std::vector<std::byte> encode_{_snake(name)}(")
        w(f"    const {name}Payload& payload) {{")
        w("  std::vector<std::byte> out;")
        for field in rec["fields"]:
            w(_cpp_encode_field(field, "payload", "out", enums))
        w("  return out;")
        w("}")
        w("")
        w(f"[[nodiscard]] inline bool decode_{_snake(name)}(")
        w("    std::span<const std::byte> data, {name}Payload& out) {{".format(name=name))
        w("  std::size_t offset = 0;")
        for field in rec["fields"]:
            w(_cpp_decode_field(field, "out", "data", "offset", enums))
        w("  return offset == data.size();")
        w("}")
        w("")

    w("}  // namespace trading::journal::v1")
    w("")
    return "\n".join(lines)


def _snake(name: str) -> str:
    out: list[str] = []
    for i, ch in enumerate(name):
        if ch.isupper() and i > 0:
            out.append("_")
        out.append(ch.lower())
    return "".join(out)


def _cpp_put_le(var: str, ctype: str, buf: str) -> str:
    if ctype == "uint8_t":
        return f"  {buf}.push_back(static_cast<std::byte>({var}));"
    if ctype == "int32_t":
        return (
            f"  for (int i = 0; i < 4; ++i) {{ {buf}.push_back(static_cast<std::byte>"
            f"(({var} >> (8 * i)) & 0xFF)); }}"
        )
    if ctype == "int64_t":
        return (
            f"  for (int i = 0; i < 8; ++i) {{ {buf}.push_back(static_cast<std::byte>"
            f"(({var} >> (8 * i)) & 0xFF)); }}"
        )
    bits = {"uint16_t": 2, "uint32_t": 4, "uint64_t": 8}[ctype]
    cast = "static_cast<std::uint64_t>" if ctype == "uint64_t" else f"static_cast<{ctype}>"
    return (
        f"  for (int i = 0; i < {bits}; ++i) {{ {buf}.push_back(static_cast<std::byte>"
        f"(({cast}({var}) >> (8 * i)) & 0xFF)); }}"
    )


def _cpp_encode_field(field: dict[str, Any], src: str, buf: str, enums: dict[str, Any]) -> str:
    name = field["name"]
    ftype = field["type"]
    lines: list[str] = []
    if ftype in CPP_TYPES and ftype != "ascii4":
        ctype = CPP_TYPES[ftype][0]
        lines.append(_cpp_put_le(f"{src}.{name}", ctype, buf))
    elif ftype == "ascii4" or (ftype == "ascii" and "size" in field):
        size = 4 if ftype == "ascii4" else field["size"]
        lines.append(f"  for (std::size_t i = 0; i < {size}; ++i) {{")
        lines.append(f"    {buf}.push_back(static_cast<std::byte>({src}.{name}[i]));")
        lines.append("  }")
    elif ftype == "bytes32":
        lines.append(f"  for (const auto b : {src}.{name}) {{ {buf}.push_back(b); }}")
    elif ftype == "utf8":
        max_len = field["max"]
        lines.append(f"  if ({src}.{name}.size() > {max_len}) {{ return {{}}; }}")
        lines.append(_cpp_put_le(f"static_cast<std::uint16_t>({src}.{name}.size())", "uint16_t", buf))
        lines.append(f"  for (unsigned char ch : {src}.{name}) {{")
        lines.append(f"    {buf}.push_back(static_cast<std::byte>(ch));")
        lines.append("  }")
    elif ftype == "enum":
        storage = field.get("storage", "u16")
        ctype = CPP_TYPES[storage][0]
        lines.append(
            _cpp_put_le(
                f"static_cast<{ctype}>(static_cast<std::underlying_type_t<{field['enum']}>>({src}.{name}))",
                ctype,
                buf,
            )
        )
    else:
        raise ValueError(field)
    return "\n".join(lines)


def _cpp_decode_field(
    field: dict[str, Any], dst: str, data: str, offset: str, enums: dict[str, Any]
) -> str:
    name = field["name"]
    ftype = field["type"]
    lines: list[str] = []
    if ftype in CPP_TYPES and ftype != "ascii4":
        ctype = CPP_TYPES[ftype][0]
        size = {"uint8_t": 1, "uint16_t": 2, "uint32_t": 4, "uint64_t": 8, "int32_t": 4, "int64_t": 8}[ctype]
        lines.append(f"  if ({offset} + {size} > {data}.size()) {{ return false; }}")
        if ctype.startswith("int"):
            lines.append(f"  {dst}.{name} = 0;")
            lines.append(f"  for (int i = {size - 1}; i >= 0; --i) {{")
            lines.append(f"    {dst}.{name} = ({dst}.{name} << 8) | static_cast<{ctype}>({data}[{offset} + i]);")
            lines.append("  }")
        else:
            lines.append(f"  {dst}.{name} = 0;")
            lines.append(f"  for (int i = {size - 1}; i >= 0; --i) {{")
            lines.append(
                f"    {dst}.{name} = static_cast<{ctype}>({dst}.{name} << 8 | "
                f"static_cast<{ctype}>({data}[{offset} + i]));"
            )
            lines.append("  }")
        lines.append(f"  {offset} += {size};")
    elif ftype == "ascii4" or (ftype == "ascii" and "size" in field):
        size = 4 if ftype == "ascii4" else field["size"]
        lines.append(f"  if ({offset} + {size} > {data}.size()) {{ return false; }}")
        lines.append(f"  for (std::size_t i = 0; i < {size}; ++i) {{")
        lines.append(f"    {dst}.{name}[i] = static_cast<char>({data}[{offset} + i]);")
        lines.append("  }")
        lines.append(f"  {offset} += {size};")
    elif ftype == "bytes32":
        lines.append(f"  if ({offset} + 32 > {data}.size()) {{ return false; }}")
        lines.append(f"  for (std::size_t i = 0; i < 32; ++i) {{")
        lines.append(f"    {dst}.{name}[i] = {data}[{offset} + i];")
        lines.append("  }")
        lines.append(f"  {offset} += 32;")
    elif ftype == "utf8":
        max_len = field["max"]
        lines.append(f"  if ({offset} + 2 > {data}.size()) {{ return false; }}")
        lines.append(f"  std::uint16_t len = 0;")
        lines.append(f"  for (int i = 1; i >= 0; --i) {{")
        lines.append(f"    len = static_cast<std::uint16_t>(len << 8 | static_cast<std::uint16_t>({data}[{offset} + i]));")
        lines.append("  }")
        lines.append(f"  {offset} += 2;")
        lines.append(f"  if (len > {max_len} || {offset} + len > {data}.size()) {{ return false; }}")
        lines.append(f"  {dst}.{name}.clear();")
        lines.append(f"  {dst}.{name}.reserve(len);")
        lines.append(f"  for (std::uint16_t i = 0; i < len; ++i) {{")
        lines.append(f"    {dst}.{name}.push_back(static_cast<char>({data}[{offset} + i]));")
        lines.append("  }")
        lines.append(f"  {offset} += len;")
    elif ftype == "enum":
        storage = field.get("storage", "u16")
        ctype = CPP_TYPES[storage][0]
        size = 1 if storage == "u8" else 2
        enum_name = field["enum"]
        lines.append(f"  if ({offset} + {size} > {data}.size()) {{ return false; }}")
        lines.append(f"  {ctype} raw_{name} = 0;")
        if size == 1:
            lines.append(f"  raw_{name} = static_cast<{ctype}>({data}[{offset}]);")
        else:
            lines.append(f"  for (int i = {size - 1}; i >= 0; --i) {{")
            lines.append(
                f"    raw_{name} = static_cast<{ctype}>(raw_{name} << 8 | "
                f"static_cast<{ctype}>({data}[{offset} + i]));"
            )
            lines.append("  }")
        lines.append(
            f"  {dst}.{name} = static_cast<{enum_name}>(static_cast<std::underlying_type_t<{enum_name}>>(raw_{name}));"
        )
        lines.append(f"  {offset} += {size};")
    else:
        raise ValueError(field)
    return "\n".join(lines)


def _cpp_header_codec() -> str:
    return """
inline std::uint32_t compute_crc32c(std::span<const std::byte> data) {
  std::uint32_t crc = 0xFFFFFFFFU;
  for (const std::byte b : data) {
    crc ^= static_cast<std::uint32_t>(b);
    for (int k = 0; k < 8; ++k) {
      crc = (crc >> 1) ^ (0x82F63B78U & static_cast<std::uint32_t>(-static_cast<std::int32_t>(crc & 1U)));
    }
  }
  return ~crc;
}

[[nodiscard]] inline std::array<std::byte, kRecordHeaderSize> encode_header(
    const RecordHeader& header, std::span<const std::byte> payload) {
  RecordHeader temp = header;
  temp.payload_length = static_cast<std::uint32_t>(payload.size());
  temp.crc32c = 0;
  std::array<std::byte, kRecordHeaderSize> raw{};
  std::memcpy(raw.data(), &temp.magic, sizeof(temp.magic));
  auto put16 = [&](std::size_t off, std::uint16_t v) {
    for (int i = 0; i < 2; ++i) {
      raw[off + i] = static_cast<std::byte>((v >> (8 * i)) & 0xFF);
    }
  };
  auto put32 = [&](std::size_t off, std::uint32_t v) {
    for (int i = 0; i < 4; ++i) {
      raw[off + i] = static_cast<std::byte>((v >> (8 * i)) & 0xFF);
    }
  };
  auto put64 = [&](std::size_t off, std::uint64_t v) {
    for (int i = 0; i < 8; ++i) {
      raw[off + i] = static_cast<std::byte>((v >> (8 * i)) & 0xFF);
    }
  };
  put16(4, temp.format_version);
  put16(6, temp.record_type);
  put64(8, temp.sequence);
  put64(16, temp.monotonic_ns);
  put64(24, temp.wall_ns);
  put32(32, temp.payload_length);
  put32(36, 0);
  std::vector<std::byte> crc_input;
  crc_input.insert(crc_input.end(), raw.begin(), raw.end());
  crc_input.insert(crc_input.end(), payload.begin(), payload.end());
  const std::uint32_t crc = compute_crc32c(crc_input);
  put32(36, crc);
  std::memcpy(raw.data() + 36, &crc, sizeof(crc));
  return raw;
}

[[nodiscard]] inline bool decode_header(std::span<const std::byte> data, RecordHeader& out) {
  if (data.size() < kRecordHeaderSize) {
    return false;
  }
  std::memcpy(&out.magic, data.data(), 4);
  auto get16 = [&](std::size_t off) {
    std::uint16_t v = 0;
    for (int i = 1; i >= 0; --i) {
      v = static_cast<std::uint16_t>(v << 8 | static_cast<std::uint16_t>(data[off + i]));
    }
    return v;
  };
  auto get32 = [&](std::size_t off) {
    std::uint32_t v = 0;
    for (int i = 3; i >= 0; --i) {
      v = v << 8 | static_cast<std::uint32_t>(data[off + i]);
    }
    return v;
  };
  auto get64 = [&](std::size_t off) {
    std::uint64_t v = 0;
    for (int i = 7; i >= 0; --i) {
      v = v << 8 | static_cast<std::uint64_t>(data[off + i]);
    }
    return v;
  };
  out.format_version = get16(4);
  out.record_type = get16(6);
  out.sequence = get64(8);
  out.monotonic_ns = get64(16);
  out.wall_ns = get64(24);
  out.payload_length = get32(32);
  out.crc32c = get32(36);
  return true;
}
""".strip()


def _cpp_crc32c() -> str:
    return ""


def emit_python(schema: dict[str, Any]) -> str:
    enums = schema["enums"]
    records = schema["records"]
    lines: list[str] = []
    w = lines.append
    w('"""Generated journal v1 bindings. Do not edit."""')
    w("")
    w("from __future__ import annotations")
    w("")
    w("import struct")
    w("from dataclasses import dataclass")
    w("from enum import IntEnum")
    w("")
    w(f"JOURNAL_MAGIC = {schema['magic']!r}")
    w(f"FORMAT_VERSION = {schema['format_version']}")
    w("RECORD_HEADER_SIZE = 40")
    w("")
    w(_py_crc32c())
    w("")
    for enum_name, members in enums.items():
        w(f"class {enum_name}(IntEnum):")
        for member in members:
            w(f"    {member['name']} = {member['value']}")
        w("")
    w("class RecordType(IntEnum):")
    for rec in records:
        w(f"    {rec['name']} = {rec['id']}")
    w("")
    w("@dataclass")
    w("class RecordHeader:")
    w("    magic: bytes")
    w("    format_version: int")
    w("    record_type: int")
    w("    sequence: int")
    w("    monotonic_ns: int")
    w("    wall_ns: int")
    w("    payload_length: int")
    w("    crc32c: int")
    w("")
    w("def encode_header(header: RecordHeader, payload: bytes) -> bytes:")
    w("    body = struct.pack('<4sHHQQQI', header.magic, header.format_version,")
    w("                         header.record_type, header.sequence, header.monotonic_ns,")
    w("                         header.wall_ns, len(payload))")
    w("    body += struct.pack('<I', 0)")
    w("    crc = compute_crc32c(body + payload)")
    w("    return body[:36] + struct.pack('<I', crc)")
    w("")
    w("def decode_header(data: bytes) -> RecordHeader:")
    w("    if len(data) < RECORD_HEADER_SIZE:")
    w("        raise ValueError('short header')")
    w("    magic, fmt, rtype, seq, mono, wall, plen, crc = struct.unpack_from('<4sHHQQQII', data, 0)")
    w("    return RecordHeader(magic, fmt, rtype, seq, mono, wall, plen, crc)")
    w("")

    for rec in records:
        name = rec["name"]
        w("@dataclass")
        w(f"class {name}Payload:")
        for field in rec["fields"]:
            w(f"    {field['name']}: {field_py_annotation(field)}")
        w("")
        w(f"def encode_{_snake(name)}(payload: {name}Payload) -> bytes:")
        w("    out = bytearray()")
        for field in rec["fields"]:
            w(_py_encode_field(field, "payload", "out", enums))
        w("    return bytes(out)")
        w("")
        w(f"def decode_{_snake(name)}(data: bytes) -> {name}Payload:")
        w("    offset = 0")
        w(f"    kwargs: dict[str, object] = {{}}")
        for field in rec["fields"]:
            w(_py_decode_field(field, "kwargs", "data", "offset", enums, name))
        w(f"    if offset != len(data):")
        w("        raise ValueError('payload length mismatch')")
        w(f"    return {name}Payload(**kwargs)  # type: ignore[arg-type]")
        w("")

    return "\n".join(lines)


def _py_crc32c() -> str:
    return """
def compute_crc32c(data: bytes) -> int:
    crc = 0xFFFFFFFF
    for b in data:
        crc ^= b
        for _ in range(8):
            crc = (crc >> 1) ^ (0x82F63B78 & -(crc & 1))
    return (~crc) & 0xFFFFFFFF
""".strip()


def _py_encode_field(field: dict[str, Any], src: str, buf: str, enums: dict[str, Any]) -> str:
    name = field["name"]
    ftype = field["type"]
    if ftype in CPP_TYPES and ftype != "ascii4":
        fmt = CPP_TYPES[ftype][1]
        return f"    {buf} += struct.pack('<{fmt}', {src}.{name})"
    if ftype == "ascii4":
        return f"    {buf} += struct.pack('4s', {src}.{name}.encode('ascii')[:4].ljust(4, b'\\0'))"
    if ftype == "ascii":
        size = field["size"]
        return (
            f"    {buf} += {src}.{name}.encode('ascii')[:{size}].ljust({size}, b'\\0')"
        )
    if ftype == "bytes32":
        return (
            f"    if len({src}.{name}) != 32:\n"
            f"        raise ValueError('{name}')\n"
            f"    {buf} += {src}.{name}"
        )
    if ftype == "utf8":
        max_len = field["max"]
        return (
            f"    raw = {src}.{name}.encode('utf-8')\n"
            f"    if len(raw) > {max_len}: raise ValueError('{name}')\n"
            f"    {buf} += struct.pack('<H', len(raw)) + raw"
        )
    if ftype == "enum":
        storage = field.get("storage", "u16")
        fmt = CPP_TYPES[storage][1]
        return f"    {buf} += struct.pack('<{fmt}', int({src}.{name}))"
    raise ValueError(field)


def _py_decode_field(
    field: dict[str, Any], dst: str, data: str, offset: str, enums: dict[str, Any], rec_name: str
) -> str:
    name = field["name"]
    ftype = field["type"]
    lines: list[str] = []
    if ftype in CPP_TYPES and ftype != "ascii4":
        fmt = CPP_TYPES[ftype][1]
        size = struct.calcsize(f"<{fmt}") if False else 0
        lines.append(f"    (val,) = struct.unpack_from('<{fmt}', {data}, {offset})")
        lines.append(f"    {dst}['{name}'] = val")
        lines.append(f"    {offset} += struct.calcsize('<{fmt}')")
    elif ftype == "ascii4":
        lines.append(f"    raw = struct.unpack_from('4s', {data}, {offset})[0]")
        lines.append(f"    {dst}['{name}'] = raw.rstrip(b'\\0').decode('ascii')")
        lines.append(f"    {offset} += 4")
    elif ftype == "ascii":
        size = field["size"]
        lines.append(f"    raw = struct.unpack_from('{size}s', {data}, {offset})[0]")
        lines.append(f"    {dst}['{name}'] = raw.rstrip(b'\\0').decode('ascii')")
        lines.append(f"    {offset} += {size}")
    elif ftype == "bytes32":
        lines.append(f"    {dst}['{name}'] = {data}[{offset}:{offset}+32]")
        lines.append(f"    {offset} += 32")
    elif ftype == "utf8":
        lines.append(f"    (ulen,) = struct.unpack_from('<H', {data}, {offset})")
        lines.append(f"    {offset} += 2")
        lines.append(f"    {dst}['{name}'] = {data}[{offset}:{offset}+ulen].decode('utf-8')")
        lines.append(f"    {offset} += ulen")
    elif ftype == "enum":
        storage = field.get("storage", "u16")
        fmt = CPP_TYPES[storage][1]
        lines.append(f"    (val,) = struct.unpack_from('<{fmt}', {data}, {offset})")
        lines.append(f"    {dst}['{name}'] = val")
        lines.append(f"    {offset} += struct.calcsize('<{fmt}')")
    else:
        raise ValueError(field)
    return "\n".join(lines)


